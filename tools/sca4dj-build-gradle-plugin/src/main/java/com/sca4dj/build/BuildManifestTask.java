package com.sca4dj.build;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.gradle.api.DefaultTask;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.MapProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;
import org.gradle.work.DisableCachingByDefault;

import java.io.IOException;
import java.nio.file.Files;
import java.util.LinkedHashMap;
import java.util.Properties;

/** 把构建事实同时写成跨技术栈清单和 Spring Boot 构建属性。 */
@DisableCachingByDefault(because = "构建时间和批次属于每次构建的事实")
public abstract class BuildManifestTask extends DefaultTask {
    /** @return 根构建确定的版本事实 */
    @Input
    public abstract MapProperty<String, String> getMetadata();

    /** @return 当前构件的稳定名称 */
    @Input
    public abstract Property<String> getComponent();

    /** @return 清单和 META-INF 的生成目录 */
    @OutputDirectory
    public abstract DirectoryProperty getOutputDirectory();

    /** 生成运行时和其他构建入口消费的相同版本字段。 */
    @TaskAction
    public void generate() throws IOException {
        var values = new LinkedHashMap<String, Object>(getMetadata().get());
        values.put("apiContractVersion", Integer.parseInt(getMetadata().get().get("apiContractVersion")));
        values.put("component", getComponent().get());
        values.put(
                "componentBuildId",
                values.get("releaseId") + "." + getComponent().get() + "."
                        + values.get("sourceRevision") + "."
                        + values.get("builtAt").toString().replaceAll("[^0-9]", ""));
        var root = getOutputDirectory().get().getAsFile().toPath();
        Files.createDirectories(root.resolve("META-INF"));
        new ObjectMapper().writerWithDefaultPrettyPrinter()
                .writeValue(root.resolve("build-manifest.json").toFile(), values);
        var properties = new Properties();
        values.forEach((key, value) -> properties.setProperty("build." + key, value.toString()));
        properties.setProperty("build.name", getComponent().get());
        properties.setProperty("build.version", values.get("buildVersion").toString());
        properties.setProperty("build.time", values.get("builtAt").toString());
        try (var output = Files.newOutputStream(root.resolve("META-INF/build-info.properties"))) {
            properties.store(output, "Generated by Gradle; do not edit");
        }
    }
}
